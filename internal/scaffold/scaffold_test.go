func project(t *testing.T, driver string) string {
	t.Helper()
	base := t.TempDir()
	opts := DefaultOptions()
	opts.Name, opts.Database = "demo", driver
	if _, err := Init(context.Background(), base, opts); err != nil {
		t.Fatal(err)
	}
	return filepath.Join(base, "demo")
}

func TestGeneratedProjectsAndDialectMigrations(t *testing.T) {
	for _, dialect := range []string{"mysql", "postgres", "sqlite", "sqlserver"} {
		t.Run(dialect, func(t *testing.T) {
			root := project(t, dialect)
			if _, err := Model(context.Background(), filepath.Join(root, "internal", "cmd"), "Todo", "Content:string,Done:bool,DueAt:*time.Time,Data:[]byte"); err != nil {
				t.Fatal(err)
			}
			if _, err := Migration(context.Background(), root, "Todo", "", true, true); err != nil {
				t.Fatal(err)
			}
			if _, err := Migration(context.Background(), root, "Todo", "", true, true); err == nil {
				t.Fatal("duplicate create migration accepted")
			}
			if _, err := Model(context.Background(), root, "User", "Email:string"); err != nil {
				t.Fatal(err)
			}
			if _, err := Migration(context.Background(), root, "User", "people", false, false); err != nil {
				t.Fatal(err)
			}
			if _, err := os.Stat(filepath.Join(root, "database/migrations/down/000002_create_people.sql")); err != nil {
				t.Fatal(err)
			}
			if err := filepath.WalkDir(root, func(path string, entry os.DirEntry, err error) error {
				if err != nil {
					return err
				}
				if !entry.IsDir() && strings.HasSuffix(path, ".go") {
					_, err = parser.ParseFile(token.NewFileSet(), path, nil, parser.AllErrors)
				}
				return err
			}); err != nil {
				t.Fatal(err)
			}
			data, err := os.ReadFile(filepath.Join(root, "database/migrations/up/000001_create_todos.sql"))
			if err != nil {
				t.Fatal(err)
			}
			identity := map[string]string{"mysql": "AUTO_INCREMENT", "postgres": "GENERATED BY DEFAULT AS IDENTITY", "sqlite": "AUTOINCREMENT", "sqlserver": "IDENTITY(1,1)"}[dialect]
			if !strings.Contains(string(data), identity) || !strings.Contains(string(data), "due_at") || !strings.Contains(string(data), " NULL") {
				t.Fatalf("invalid %s schema: %s", dialect, data)
			}
		})
	}
}

func TestRefusesUnsafeAndConflictingOutputs(t *testing.T) {
	root := project(t, "sqlite")
	for _, name := range []string{"../Escape", "todo", "Todo/Other", "type", ""} {
		if _, err := Model(context.Background(), root, name, ""); err == nil {
			t.Fatalf("invalid model accepted: %q", name)
		}
	}
	for _, fields := range []string{"ID:int", "Content:string,Content:bool", "Value:map[string]string", "Value:**string"} {
		if _, err := Model(context.Background(), root, "Todo", fields); err == nil {
			t.Fatalf("invalid fields accepted: %q", fields)
		}
	}
	if _, err := Model(context.Background(), root, "Todo", ""); err != nil {
		t.Fatal(err)
	}
	if _, err := Migration(context.Background(), root, "Todo", "todos; DROP TABLE users", true, true); err == nil {
		t.Fatal("invalid table accepted")
	}
	if _, err := writeFiles(context.Background(), root, map[string][]byte{"models/todo.go": []byte("overwritten"), "models/other.go": []byte("partial")}); err == nil {
		t.Fatal("overwrite accepted")
	}
	if _, err := os.Stat(filepath.Join(root, "models/other.go")); !os.IsNotExist(err) {
		t.Fatal("partial output left on conflict")
	}
	before, err := os.ReadFile(filepath.Join(root, "main.go"))
	if err != nil {
		t.Fatal(err)
	}
	opts := DefaultOptions()
	opts.Name = "demo"
	if _, err := Init(context.Background(), filepath.Dir(root), opts); err == nil {
		t.Fatal("existing project overwritten")
	}
	after, err := os.ReadFile(filepath.Join(root, "main.go"))
	if err != nil || string(before) != string(after) {
		t.Fatal("existing project changed")
	}
}

func TestInvalidOptionsLeaveNoFiles(t *testing.T) {
	for _, modify := range []func(*Options){
		func(o *Options) { o.Name = "../outside" },
		func(o *Options) { o.Module = "example.com/../bad" },
		func(o *Options) { o.DBPort = 70000 },
		func(o *Options) { o.FrameworkVersion = "latest" },
		func(o *Options) { o.Address = "value\nDB_PASSWORD=secret" },
	} {
		root := t.TempDir()
		opts := DefaultOptions()
		opts.Name = "demo"
		modify(&opts)
		if _, err := Init(context.Background(), root, opts); err == nil {
			t.Fatal("invalid options accepted")
		}
		entries, err := os.ReadDir(root)
		if err != nil || len(entries) != 0 {
			t.Fatalf("partial project left: %v %v", entries, err)
		}
	}
}
